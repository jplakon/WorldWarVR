const ExecutableProfile* find_supported_profile(
    const std::uint64_t file_size, const Sha256Digest& sha256) noexcept {
    const auto profiles = supported_profiles();
    const auto found = std::find_if(
        profiles.begin(), profiles.end(),
        [file_size, &sha256](const ExecutableProfile* profile) {
            return profile->file_size == file_size && profile->sha256 == sha256;
        });
    return found == profiles.end() ? nullptr : *found;
}

const HookSite* find_hook_site(const ExecutableProfile& profile,
                               const HookSiteId id) noexcept {
    const auto found = std::find_if(profile.sites.begin(), profile.sites.end(),
                                    [id](const HookSite& site) { return site.id == id; });
    return found == profile.sites.end() ? nullptr : &*found;
}

const DataSymbol* find_data_symbol(const ExecutableProfile& profile,
                                   const DataSymbolId id) noexcept {
    const auto found =
        std::find_if(profile.data_symbols.begin(), profile.data_symbols.end(),
                     [id](const DataSymbol& symbol) { return symbol.id == id; });
    return found == profile.data_symbols.end() ? nullptr : &*found;
}

